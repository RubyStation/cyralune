export function savedN7xPoster(name = '') {
  const slug = String(name).toLocaleLowerCase().normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return savedPosterSlugs.has(slug) ? `./assets/posters/${slug}.jpg` : '';
}

