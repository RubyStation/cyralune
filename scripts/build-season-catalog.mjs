// Generate season boundaries only when a TVmaze episode guide matches the
// imported episode titles. Unknown boundaries remain numbered episode ranges.
// Usage: node scripts/build-season-catalog.mjs
import {writeFile} from 'node:fs/promises';
import {ANIME_GALLERY} from '../nyx-static/anime-gallery.js';
import {ANVIL_CATALOG} from '../nyx-static/anvil-catalog.js';
import {normalizedTitle} from '../nyx-static/banner-catalog.js';

const shows = new Map();
for (const show of [...ANIME_GALLERY,...ANVIL_CATALOG]) {
  const key = normalizedTitle(show.name);
  const id = Number(show.sourceUrl?.match(/tvmaze\.com\/shows\/(\d+)/)?.[1]);
  if (!key || !id || !Array.isArray(show.episodeTitles)) continue;
  if (!shows.has(key) || shows.get(key).episodeTitles.length < show.episodeTitles.length)
    shows.set(key,{...show,id});
}
const keyTitle = title => String(title || '').toLocaleLowerCase().normalize('NFKD')
  .replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]+/g,'');
const found = {}, missing = [];
let cursor = 0;
const items = [...shows.entries()];

async function worker() {
  while (cursor < items.length) {
    const [key,show] = items[cursor++];
    try {
      const res = await fetch(`https://api.tvmaze.com/shows/${show.id}/episodes`,{
        signal:AbortSignal.timeout(25000)
      });
      if (!res.ok) throw Error(`HTTP ${res.status}`);
      const entries = (await res.json()).filter(x => Number.isInteger(x.season) && x.season > 0 && x.number > 0);
      const count = show.episodeTitles.length;
      if (count < 1 || entries.length < count) continue;
      const prefix = entries.slice(0,count);
      const matching = prefix.filter((ep,i) => keyTitle(ep.name) === keyTitle(show.episodeTitles[i])).length;
      if (matching / count < .92) continue;
      const seasons = [];
      for (const [i,ep] of prefix.entries()) {
        const last = seasons.at(-1);
        if (last?.season === ep.season) last.end = i+1;
        else seasons.push({season:ep.season,start:i+1,end:i+1});
      }
      if (seasons.length)
        found[key] = seasons.map(({season,start,end}) => ({start,end,name:`Season ${season}`}));
    } catch (err) { missing.push(`${show.name}: ${err.message}`); }
  }
}
await Promise.all(Array.from({length:5},()=>worker()));
const ordered = Object.fromEntries(Object.entries(found).sort(([a],[b])=>a.localeCompare(b)));
await writeFile(new URL('../nyx-static/season-catalog.js',import.meta.url),
  `// Verified season boundaries from TVmaze episode titles.\n`+
  `// Generated by scripts/build-season-catalog.mjs.\n`+
  `export const VERIFIED_SEASONS = Object.freeze(${JSON.stringify(ordered,null,2)});\n`);
console.log(JSON.stringify({seriesChecked:items.length,verified:Object.keys(ordered).length,errors:missing},null,2));
